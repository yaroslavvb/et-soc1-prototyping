#!/usr/bin/env python3
"""Generate the V3-DTF kernel cases (modes 300+) and the host's table for them.

    python3 workloads/enercat/gen_df.py      # writes kernel/enercat_df.inc, enercat_df.h, enercat_df_modes.json

Compiled only with -DENERCAT_DF=ON (build/enercat-df): without it the kernel ELF is the catalogue's, unchanged, because
the cases are spliced into enercat.c's switch behind #ifdef and gen_ops.py's numbering is untouched.
tools/claims-v3/dtf/README.md has why each shape exists. Every shape has eight distinct sinks f8..f15, no sink is ever read,
and every DF run is --harts 1 (tools/claims-v3/dtf/make_dtf.py writes that into the manifest).

- c2: "op f8,f0,f7 ... op f15,f3,f7": four rotating first sources f0..f3, the second source f7 held. The rotating block of
  gen_ops.py cannot hold a port still (op i reads f_i and f_i+1); E-D2 and E-D3 need one held.
- un1a / un1b: 16 x fnot.pi. 1A repeats the 8-op block, so every sink gets the same value every time (no register-file
  cell flips); 1B rotates the second half's sinks by three, so each sink is written alternately from an even and an odd
  source (8h cell bits flip per op) at a minimum reuse distance of 3 ops. Sources, results and op count are identical.
- addr: "fxor.pi f(8+i), fR, fR" with R alternating f0 and fX (X = 0, 1, 7, 31): the register index on both read ports
  changes by popcount(X) bits per op while every data bit stays the same (f ^ f = 0). f30 and f31 are zeroed once,
  outside RUN, and fenced with fmv.x.w x0 (errata 1.29, docs/et-soc1-notes.md).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FIRST = 300
SINKS = ", ".join(f'"f{8 + i}"' for i in range(8))


def c2(op):
    return [f"{op} f{8 + i}, f{i % 4}, f7" for i in range(8)]


def un1a():
    return [f"fnot.pi f{8 + i}, f{i}" for i in range(8)] * 2


def un1b():
    return [f"fnot.pi f{8 + i}, f{i}" for i in range(8)] + [f"fnot.pi f{8 + (i + 3) % 8}, f{i}" for i in range(8)]


def addr(x):
    return [f"fxor.pi f{8 + i}, f{0 if i % 2 == 0 else x}, f{0 if i % 2 == 0 else x}" for i in range(8)]


ADDR_PROLOGUE = "fxor.pi f30, f0, f0\\nfxor.pi f31, f0, f0\\nfmv.x.w x0, f30\\nfmv.x.w x0, f31"

MODES = [
    ("df.c2.fand", c2("fand.pi"), False, "E-D2: fand.pi, second source f7 held"),
    ("df.c2.for", c2("for.pi"), False, "E-D2: for.pi, second source f7 held"),
    ("df.c2.fadd", c2("fadd.pi"), False, "E-D3: fadd.pi, second source f7 held"),
    ("df.c2.fxor", c2("fxor.pi"), False, "gate ladder: fxor.pi, second source f7 held"),
    ("df.un1a.fnot", un1a(), False, "E-D1 1A: 16 fnot.pi, every sink rewritten with the same value"),
    ("df.un1b.fnot", un1b(), False, "E-D1 1B: 16 fnot.pi, second half's sinks rotated by 3 (cells flip)"),
    ("df.addr.a0", addr(0), True, "E-D5: fxor.pi fR,fR with R = f0 always (index distance 0)"),
    ("df.addr.a1", addr(1), True, "E-D5: R alternating f0 / f1 (index distance 1)"),
    ("df.addr.a3", addr(7), True, "E-D5: R alternating f0 / f7 (index distance 3)"),
    ("df.addr.a5", addr(31), True, "E-D5: R alternating f0 / f31 (index distance 5)"),
]


def main():
    inc = ["// Generated by gen_df.py: the V3-DTF cases (modes 300+), spliced into enercat.c's switch under ENERCAT_DF.",
           "// Do not edit; re-run gen_df.py."]
    rows, table = [], []
    for k, (name, ops, prologue, note) in enumerate(MODES):
        mode = FIRST + k
        per_iter = 8 * len(ops)   # RUN repeats the block eight times per iteration
        body = "\\n".join(ops)
        clob = SINKS + (', "f30", "f31"' if prologue else "")
        inc.append(f"    case {mode}: /* {name} */")
        inc.append("        load_vsrc(src);")
        if prologue:
            inc.append(f'        __asm__ __volatile__("{ADDR_PROLOGUE}" : : : "f30", "f31");')
        inc.append(f'        RUN(__asm__ __volatile__("{body}" : : : {clob}));')
        inc.append("        break;")
        rows.append(f'  {{"{name}", {mode}, {per_iter}, "instruction", false, "{note}"}},')
        table.append({"name": name, "mode": mode, "ops_per_iter": per_iter, "ops": ops, "prologue": ADDR_PROLOGUE.split("\\n") if prologue else [],
                      "note": note})
    with open(os.path.join(HERE, "kernel", "enercat_df.inc"), "w") as f:
        f.write("\n".join(inc) + "\n")
    with open(os.path.join(HERE, "enercat_df.h"), "w") as f:
        f.write("// Generated by gen_df.py: the V3-DTF modes (ids 300+), for kernel and host. Compiled only with ENERCAT_DF.\n"
                "#pragma once\n"
                f"#define EC_DF_FIRST {FIRST}\n#define EC_DF_COUNT {len(MODES)}\n"
                "#ifdef __cplusplus\n#include <vector>\n#include \"enercat_modes.h\"\n"
                "static const std::vector<EcGenMode> EC_DF_MODES = {\n" + "\n".join(rows) + "\n};\n#endif\n")
    with open(os.path.join(HERE, "enercat_df_modes.json"), "w") as f:
        json.dump({"first": FIRST, "modes": table}, f, indent=1)
    print(f"{len(MODES)} DF modes, {FIRST}..{FIRST + len(MODES) - 1}")


if __name__ == "__main__":
    main()
