#!/usr/bin/env python3
"""Write kernel/x04_blocks.inc: the 512-slot loop bodies of the X04_MIX arms.

One loop body is 512 four-byte slots (RVC off, so every no-op is a full `addi x0, x0, 0`). In a body for class C
and spacing P, slot i holds an instruction of class C when i % P == 0 and a no-op otherwise, so the issue count per
loop is the same in every arm (512) and only the fraction of slots that hold the class changes: 1/P.
A clustered body (cluster = 1) holds the same 512/P class instructions, all in a row at the body's start, then
no-ops: the same instructions and the same issue count, in a different order.

Class instructions read f0..f7 (zeros, loaded once) and write f8..f15, rotating, and nothing ever reads f8..f15.
Usage: python3 gen_blocks.py > kernel/x04_blocks.inc
"""
import sys

SLOTS = 512
SPACINGS = (1, 2, 4, 8, 16, 32, 64)
CLASSES = {  # id: (name, mnemonic)
    1: ("FSGNJ_S", "fsgnj.s"),
    2: ("FADD_S", "fadd.s"),
    3: ("FADD_PS", "fadd.ps"),
    4: ("FSGNJ_PS", "fsgnj.ps"),
}
CLUSTERED = ((3, 8), (3, 16))  # (class id, spacing) pairs that also get a clustered body


def body(mnemonic, spacing, cluster):
    lines, k = [], 0
    for i in range(SLOTS):
        hit = (i < SLOTS // spacing) if cluster else (i % spacing == 0)
        if hit:
            d, s1, s2 = 8 + (k % 8), k % 8, (k + 1) % 8
            lines.append("%s f%d, f%d, f%d" % (mnemonic, d, s1, s2))
            k += 1
        else:
            lines.append("addi x0, x0, 0")
    return lines


def emit(out, cid, mnem, p, cluster):
    out.write("case X04_MIX_CASE(%d, %d, %d): /* %s, %d of 512 slots, %s */\n"
              % (cid, p, cluster, mnem, SLOTS // p, "in a row" if cluster else "one in every %d" % p))
    out.write("    RUN_SLED(\n")
    for ln in body(mnem, p, cluster):
        out.write('        "%s\\n"\n' % ln)
    out.write("    );\n    break;\n")


def main():
    out = sys.stdout
    out.write("/* Generated by gen_blocks.py: do not edit. The X04_MIX loop bodies, 512 slots each. */\n")
    for cid, (name, mnem) in sorted(CLASSES.items()):
        for p in SPACINGS:
            emit(out, cid, mnem, p, 0)
    for cid, p in CLUSTERED:
        emit(out, cid, CLASSES[cid][1], p, 1)


if __name__ == "__main__":
    main()
