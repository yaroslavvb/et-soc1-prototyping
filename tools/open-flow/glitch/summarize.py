#!/usr/bin/env python3
"""Q138(g): the tables and the summary, from analyze_glitch.py's and refit_k.py's outputs.

    summarize.py --dir <data dir> --out-md tables.md --out-json summary.json
Reads glitch_<arm-of-run>.json files named in RUNS below and refit_k.json, if present.
"""
import argparse, json, math, os
ARMS = ["booth_tree", "booth", "booth_swap", "plain"]
RUNS = [("glitch_mid.json", "primary: liberty delays, a VHDL-like inertial rule, the middle launch point"),
        ("glitch_3pt.json", "the three launch points' mean"),
        ("glitch_vstyle.json", "Verilog's inertial rule (middle point)"),
        ("glitch_skew150.json", "input ports skewed 0-150 ps at random, bit by bit (middle point)"),
        ("glitch_wire0.json", "no wire load, pin capacitance only (middle point)"),
        ("glitch_wire3.json", "three times the wire load (middle point)"),
        ("glitch_jitter20.json", "every cell's delays scaled by its own random factor in [0.8, 1.2] (middle point)")]
C_RB = 0.81                                                             # E78's frozen rail-per-board constant
E138_RAIL = [17.9, 56.2, 31.2, 65.4, 46.8, 61.6, 47.4, 82.7]
E130_A_BOARD = [83.0, 77.2, 71.8, 78.0, 87.7, 82.3, 78.7, 156.7]
E130_B_BOARD = [3.3, 44.0, 22.1, 67.2, 46.8, 62.5, 47.7, 98.9]


def rms(a, b):
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)) / len(a))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--out-md", required=True)
    ap.add_argument("--out-json", required=True)
    a = ap.parse_args()
    runs = [(f, lab, json.load(open(os.path.join(a.dir, f)))) for f, lab in RUNS if os.path.exists(os.path.join(a.dir, f))]
    E138_RAIL[:] = runs[0][2]["card_bits"]["E138_rail_B"]          # read from the committed scored.json by analyze_glitch.py
    E130_A_BOARD[:] = runs[0][2]["card_bits"]["E130_board_A"]
    refit = json.load(open(os.path.join(a.dir, "refit_k.json"))) if os.path.exists(os.path.join(a.dir, "refit_k.json")) else None
    S = {"runs": {}, "oos": {}, "refit": {}}
    L = ["# Q138(g) tables (generated by summarize.py from the JSON files beside it)", ""]
    card = runs[0][2]["card"]
    L += ["The card's intervals (95%): B odd ÷ even E138 rail **1.91 [1.71, 2.16]** (E130 rail 1.79 [1.68, 1.92], E130 board 2.41 "
          "[1.26, 38.2]); A odd ÷ even E130 **0.98 [0.92, 1.04]**; A sign, B = 0x55 ÷ B = 1, E130 **1.43 [1.36, 1.51]**. In board fJ: "
          "B odd − even +35.9 [+30.5, +41.4] (E138, rail at c_rb 0.81), +33.8 [+11.0, +56.7] (E130 board); A odd − even −1.7 [−6.6, "
          "+3.2]; A sign step +67.8 [+58.8, +76.8]; B mean bits 0–6 +41.9 [+28.3, +55.6]; A mean bits 0–6 +79.8 [+75.9, +83.8].", ""]
    L += ["## Every arm at a glance: the glitch-aware shapes (zero delay first row)", "",
          "| run | netlist | B odd ÷ even | A odd ÷ even | A sign dense ÷ one | A sign word 2 ÷ 1 |", "|---|---|---:|---:|---:|---:|"]
    zrow = {}
    for f, lab, r in runs:
        for arm in ARMS:
            o = r["arms"].get(arm)
            if not o or "glitch_fJ" not in o:
                continue
            if f == "glitch_mid.json":
                z = o["zero_delay_fJ"]
                L.append(f"| zero delay (Q136(a), middle point) | `{arm}` | {z['B_odd_over_even']:.2f} | {z['A_odd_over_even']:.2f} | {z['A_sign_dense_over_one']:.2f} | {z['A_sign_w2_over_w1']:.2f} |")
    for f, lab, r in runs:
        for arm in ARMS:
            o = r["arms"].get(arm)
            if not o or "glitch_fJ" not in o:
                continue
            g = o["glitch_fJ"]
            L.append(f"| {lab} | `{arm}` | {g['B_odd_over_even']:.2f} | {g['A_odd_over_even']:.2f} | {g['A_sign_dense_over_one']:.2f} | {g['A_sign_w2_over_w1']:.2f} |")
    L += ["", "The card: 1.91 [1.71, 2.16] (E138 rail), 0.98 [0.92, 1.04], 1.43 [1.36, 1.51] (E130 board); A sign word 2 ÷ 1 1.02 [0.98, 1.07].", ""]
    for f, lab, r in runs:
        L += [f"## {lab} (`{f}`)", ""]
        L += ["| netlist | count | B odd ÷ even | A odd ÷ even | A sign dense ÷ one | A sign word 2 ÷ 1 | B odd − even, fJ | A odd − even, fJ | A sign step, fJ | B mean 0–6, fJ | A mean 0–6, fJ | mismatches, late |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
        S["runs"][f] = {}
        for arm in ARMS:
            o = r["arms"].get(arm)
            if not o or "glitch_fJ" not in o:
                continue
            S["runs"][f][arm] = {}
            for key, nm in (("zero_delay_fJ", "zero delay (frozen)"), ("glitch_fJ", "**glitch-aware**")):
                g = o[key]
                inB = card["B_odd_over_even"]["E138_rail"][1] <= g["B_odd_over_even"] <= card["B_odd_over_even"]["E138_rail"][2]
                inA = card["A_odd_over_even"]["E130_board"][1] <= g["A_odd_over_even"] <= card["A_odd_over_even"]["E130_board"][2]
                inS = card["A_sign_dense_over_one"]["E130_board"][1] <= g["A_sign_dense_over_one"] <= card["A_sign_dense_over_one"]["E130_board"][2]
                inW = card["A_sign_w2_over_w1"]["E130_board"][1] <= g["A_sign_w2_over_w1"] <= card["A_sign_w2_over_w1"]["E130_board"][2]
                mark = lambda v, i: f"{v:.2f}" + (" ✓" if i else "")
                L.append(f"| `{arm}` | {nm} | {mark(g['B_odd_over_even'], inB)} | {mark(g['A_odd_over_even'], inA)} | "
                         f"{mark(g['A_sign_dense_over_one'], inS)} | {mark(g['A_sign_w2_over_w1'], inW)} | {g['B_odd_minus_even']:+.1f} | {g['A_odd_minus_even']:+.1f} | "
                         f"{g['A_sign_dense_minus_one']:+.1f} | {g['B_mean_bits0to6']:.1f} | {g['A_mean_bits0to6']:.1f} | "
                         + ("not checked (an arm) |" if f not in ("glitch_mid.json", "glitch_3pt.json") else f"{o['checks']['mismatch']}, {o['checks']['late']} |"))
                S["runs"][f][arm][key] = {k: g[k] for k in ("B_odd_over_even", "A_odd_over_even", "A_sign_dense_over_one", "A_sign_w2_over_w1",
                                                          "B_odd_minus_even", "A_odd_minus_even", "A_sign_dense_minus_one",
                                                          "B_mean_bits0to6", "A_mean_bits0to6", "B_list", "A_list")}
                S["runs"][f][arm][key]["inside"] = {"B_ratio": inB, "A_ratio": inA, "A_sign_ratio": inS, "A_sign_w2_ratio": inW}
            S["runs"][f][arm]["glitch_weight_scan"] = o.get("glitch_weight_scan")
        L += ["", "✓ = inside the card's interval (B: E138's rail; A: E130's board). fJ at each netlist's frozen k (Q136(a)).", ""]
        L += ["Per bit, fJ per flipped bit (bits 0–7; zero delay → glitch-aware):", "",
              "| netlist | list | " + " | ".join(f"bit {i}" for i in range(8)) + " |", "|---|---|" + "---:|" * 8]
        for arm in ARMS:
            o = r["arms"].get(arm)
            if not o or "glitch_fJ" not in o:
                continue
            for side in ("B", "A"):
                z, g = o["zero_delay_fJ"][f"{side}_list"], o["glitch_fJ"][f"{side}_list"]
                L.append(f"| `{arm}` | {side} | " + " | ".join(f"{x:.0f} → **{y:.0f}**" for x, y in zip(z, g)) + " |")
        L += ["", "Glitch weight w (counts = zero delay + w × excess; w = 1 is every inertial glitch a full toggle): the ranges of w in "
              "[0, 2] where each shape is inside the card's interval:", "",
              "| netlist | B odd ÷ even in E138 | A odd ÷ even in E130 | A sign ratio in E130 | A sign word 2 ÷ 1 in E130 | the three A shapes together | all four | B ratio at w = 0, 0.5, 1, 2; its limit |", "|---|---|---|---|---|---|---|---|"]
        for arm in ARMS:
            o = r["arms"].get(arm)
            if not o or "glitch_weight_scan" not in o:
                continue
            w = o["glitch_weight_scan"]
            fm = lambda x: "never" if not x else f"{x[0]:.2f}–{x[1]:.2f}"
            fl = lambda xs: "never" if not xs else f"{xs[0]:.2f}–{xs[-1]:.2f}"
            L.append(f"| `{arm}` | {fm(w['w_range_B_ratio_in_E138'])} | {fm(w['w_range_A_ratio_in_E130'])} | "
                     f"{fm(w['w_range_A_sign_ratio_in_E130'])} | {fm(w['w_range_A_sign_w2_ratio_in_E130'])} | {fl(w['w_A_side_all_three'])} | {fl(w['w_all_four'])} | "
                     + ", ".join(f"{w['B_ratio_at'][k]:.2f}" for k in ("0", "0.5", "1.0", "2.0")) + f"; {w['B_ratio_as_w_grows_without_bound']:.2f} |")
        L.append("")
    # out-of-sample: the netlists' per-bit prices against the card's, no fit to the bits (k from E78's kinds; c_rb 0.81 for the rail)
    base = runs[0][2]
    L += ["## Out of sample: each netlist's per-bit prices against the card's, nothing fitted to the bits", "",
          "B bits 0–6 against E138's rail (predicted rail fJ = 0.81 × board fJ), A bits 0–6 against E130's board. k: the frozen "
          "zero-delay fit (Q136(a)); for the glitch-aware count also the glitch-aware refit of M2 on E78's kinds (refit_k.json).", "",
          "| netlist | count, k | B rms, rail fJ | B r | A rms, board fJ | A r | B odd − even, fJ | A sign step, fJ |", "|---|---|---:|---:|---:|---:|---:|---:|"]
    def corr(x, y):
        mx, my = sum(x) / len(x), sum(y) / len(y)
        c = sum((p - mx) * (q - my) for p, q in zip(x, y))
        return c / math.sqrt(sum((p - mx) ** 2 for p in x) * sum((q - my) ** 2 for q in y))
    flat_B = [sum(E138_RAIL[:7]) / 7] * 7
    L.append(f"| (in sample: one price for every B bit, at the card's own mean) | — | {rms(flat_B, E138_RAIL[:7]):.1f} | — | — | — | — | — |")
    for arm in ARMS:
        o = base["arms"].get(arm)
        if not o or "glitch_fJ" not in o:
            continue
        rows = [("zero delay, frozen k", o["zero_delay_fJ"], 1.0), ("glitch-aware, frozen k", o["glitch_fJ"], 1.0)]
        if refit and arm in refit["arms"] and "single_bits_at_refit_k" in refit["arms"][arm]:
            rk = refit["arms"][arm]["single_bits_at_refit_k"]
            rows.append((f"glitch-aware, refit k {rk['k_refit_fJ']:.3f}", o["glitch_fJ"], rk["scale"]))
            kz = refit["arms"][arm]["zero_delay"]["coef_fJ"]["dnets"]
            if abs(kz - o["k_fJ"]) > 0.0005:                  # the middle-point refit; equal to the frozen k in all four
                rows.insert(1, (f"zero delay, k {kz:.3f} (middle point)", o["zero_delay_fJ"], kz / o["k_fJ"]))
        S["oos"][arm] = []
        for nm, g, sc in rows:
            pb = [C_RB * sc * x for x in g["B_list"][:7]]
            pa = [sc * x for x in g["A_list"][:7]]
            e = {"count": nm, "B_rms_rail_fJ": rms(pb, E138_RAIL[:7]), "B_r": corr(pb, E138_RAIL[:7]),
                 "A_rms_board_fJ": rms(pa, E130_A_BOARD[:7]), "A_r": corr(pa, E130_A_BOARD[:7]),
                 "B_odd_minus_even_fJ": sc * g["B_odd_minus_even"], "A_sign_step_fJ": sc * g["A_sign_dense_minus_one"]}
            S["oos"][arm].append(e)
            L.append(f"| `{arm}` | {nm} | {e['B_rms_rail_fJ']:.1f} | {e['B_r']:+.2f} | {e['A_rms_board_fJ']:.1f} | {e['A_r']:+.2f} | "
                     f"{e['B_odd_minus_even_fJ']:+.1f} | {e['A_sign_step_fJ']:+.1f} |")
    L += ["", "For comparison, E138's per-position prices predict E130's rail B bits 0–6 at 3.2 rail fJ rms (7%), parity at 7.2, "
          "flat at 13.6 (E138 `scored.json` › `out_of_sample_e130`).", ""]
    if refit:
        L += ["## M2 on E78's 15 int8 kinds, zero delay against glitch-aware (middle launch point)", "",
              "| netlist | count | k, fJ per net toggle | a, fJ per clocked bit | rms, W | leave-one-kind-out rms, W | bias, W |",
              "|---|---|---:|---:|---:|---:|---:|"]
        for arm in ARMS:
            x = refit["arms"].get(arm)
            if not x or "zero_delay" not in x:
                continue
            for key, nm in (("zero_delay", "zero delay"), ("glitch_aware", "**glitch-aware**")):
                f_ = x[key]
                L.append(f"| `{arm}` | {nm} | {f_['coef_fJ']['dnets']:.3f} ± {f_['coef_jackknife_se_fJ']['dnets']:.3f} | "
                         f"{f_['coef_fJ']['dclk']:.2f} ± {f_['coef_jackknife_se_fJ']['dclk']:.2f} | {f_['rms_w']:.3f} | {f_['loo']['rms_w']:.3f} | {f_['bias_w']:+.3f} |")
            S["refit"][arm] = {k: {"k": x[k]["coef_fJ"]["dnets"], "k_se": x[k]["coef_jackknife_se_fJ"]["dnets"], "a": x[k]["coef_fJ"]["dclk"],
                                   "rms_w": x[k]["rms_w"], "loo_rms_w": x[k]["loo"]["rms_w"], "bias_w": x[k]["bias_w"]} for k in ("zero_delay", "glitch_aware")}
            t3 = x.get("glitch_term")
            if t3:
                kk, kg, se = t3["coef_fJ"]["dnets_zero"], t3["coef_fJ"]["excess_unit"], t3["coef_jackknife_se_fJ"]["excess_unit"]
                S["refit"][arm]["glitch_term"] = {"k": kk, "k_g": kg, "k_g_se": se, "w": kg / kk, "w_se_approx": se / kk,
                                                  "se_from_w1": (kk - kg) / se, "rms_w": t3["rms_w"], "loo_rms_w": t3["loo"]["rms_w"]}
                L.append(f"| `{arm}` | glitches as their own term | k {kk:.3f}, k_g {kg:+.3f} ± {se:.3f} (w = k_g/k = {kg / kk:+.2f}; w = 1 is "
                         f"{(kk - kg) / se:.1f} s.e. away) | {t3['coef_fJ']['dclk']:.2f} | {t3['rms_w']:.3f} | {t3['loo']['rms_w']:.3f} | {t3['bias_w']:+.3f} |")
        L += ["", "Per kind, the unit's toggles timed ÷ zero delay (kind minus zeros):", "",
              "| kind | " + " | ".join(f"`{a}`" for a in ARMS if a in refit['arms'] and 'kinds' in refit['arms'][a]) + " |",
              "|---|" + "---:|" * len([a for a in ARMS if a in refit['arms'] and 'kinds' in refit['arms'][a]])]
        ks = None
        for arm in ARMS:
            if arm in refit["arms"] and "kinds" in refit["arms"][arm]:
                ks = list(refit["arms"][arm]["kinds"])
                break
        for kd in ks or []:
            fmt = lambda v: "— (no toggle)" if v is None else f"{v:.2f}"
            L.append(f"| `{kd}` | " + " | ".join(fmt(refit['arms'][a]['kinds'][kd]['unit_timed_over_zero']) for a in ARMS
                                                 if a in refit['arms'] and 'kinds' in refit['arms'][a]) + " |")
        L.append("")
    open(a.out_md, "w").write("\n".join(L) + "\n")
    json.dump(S, open(a.out_json, "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
