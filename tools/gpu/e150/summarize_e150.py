"""E150's summary tables, from the committed outputs (no refit, no new number):

    python summarize_e150.py <data dir> > summary.md

Reads choice-s.json, reduce-L.json, predictions-e150.json, reduce-H.json, score-e150.json and E149's
reduce-stage1.json / predictions-e149.json (for the same kinds on the A100).
"""
import json
import os
import sys

import numpy as np


def j(d, n):
    p = os.path.join(d, n)
    return json.load(open(p)) if os.path.exists(p) else None


def f(x, nd=1):
    return "—" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def main(d):
    d149 = os.path.join(d, "..", "2026-11-02-e149-gpu-model-check")
    ch, rL, pz, rH, sc = (j(d, n) for n in ("choice-s.json", "reduce-L.json", "predictions-e150.json",
                                              "reduce-H.json", "score-e150.json"))
    r149 = j(d149, "reduce-stage1.json")
    p149 = j(d149, "predictions-e149.json")
    s149 = j(d149, "score-e149.json")
    print("# E150 summary (generated by tools/gpu/e150/summarize_e150.py)\n")
    if ch:
        print(f"## The smoke's choice: **{ch['chosen']}**, sizes {ch.get('sizes')}, dropped {ch.get('dropped')}\n")
        print("| GPU | limit W | format | size | random W | zeros W | signal W |\n|---|---|---|---|---|---|---|")
        for g, v in ch["gpus"].items():
            for fm, c in v.get("choice", {}).items():
                n = c["size"]
                w = v["windows"]
                rr = w.get(f"{fm}.rand@{n}", {}) if n else {}
                zz = w.get(f"{fm}.zeros@{n}", {}) if n else {}
                print(f"| {g} | {f(v['limit_w'], 0)} | {fm} | {n} | {f(rr.get('p_w'))} | {f(zz.get('p_w'))} | "
                      f"{f(c['signal_w'])} |")
        print()
        print("| GPU | window | W | SM min / mean MHz | reason bits | valid | TFLOPS |\n|---|---|---|---|---|---|---|")
        for g, v in ch["gpus"].items():
            for k, w in sorted(v.get("windows", {}).items(), key=lambda kv: (kv[1]["n"], kv[0])):
                print(f"| {g} | {k} | {f(w['p_w'])} | {w['sm_min']} / {f(w['sm_mean'], 0)} | {hex(w['rsn_or'] or 0)} | "
                      f"{w['valid']} | {f(w['tflops'])} |")
        print()
    if pz:
        print(f"## Phase L (the scale's fit set): span S2 = {f(pz['span_w'])} W (bf16 randn over zeros)\n")
        print("| rule | E150 | E149 |\n|---|---|---|")
        for k, v in pz["rules_L"].items():
            print(f"| {k} | {v['verdict']} | {pz['e149_rules_stage1'].get(k)} |")
        print()
        print("| model | scale A | scale B | in-sample rms on L, A / B (W) |\n|---|---|---|---|")
        for m, s in pz["scales"].items():
            a, b = sorted(s["per_board"])
            print(f"| {m} | {f(s['per_board'][a], 3)} | {f(s['per_board'][b], 3)} | {f(s['rms_in_L'][a])} / "
                  f"{f(s['rms_in_L'][b])} |")
        print()
        print("rate ratio (E150 TFLOPS / E149 TFLOPS):", {u: {k: f(v, 3) for k, v in r.items()}
                                                         for u, r in pz["rate_ratio"].items()},
              "; E150 TFLOPS:", {u: {k: f(v) for k, v in r.items()} for u, r in pz["tflops_e150"].items()},
              "; E149:", {k: f(v) for k, v in pz["tflops_e149"].items()}, "\n")
        print("| phase-L kind | y E150 (W) | se | G1 fitted (W, A / B) | y E149 (W) |\n|---|---|---|---|---|")
        for k, v in sorted(pz["fit_L"].items()):
            fa = v["fit_G1"]
            y9 = (r149 or {}).get("kinds", {}).get(k, {}).get("y")
            print(f"| {k} | {f(v['y'])} | {f(v['se'])} | {' / '.join(f(fa[u]) for u in sorted(fa))} | {f(y9)} |")
        print()
        h = pz["heat"]
        print("heat (phase L):", {k: (round(h["pooled"][k], 4) if isinstance(h["pooled"][k], float) else
                                      h["pooled"][k]) for k in ("tau1", "tau2", "r1", "r2", "R_ss", "F30", "rms")},
              "per unit R_ss", {u: round(v["R_ss"], 4) for u, v in h["per_unit"].items()},
              "lambda", round(h["lambda_w_per_c"], 3), "lambda r1", round(h["lambda_r1"], 4),
              "sigma_cross", h["sigma_cross_c"], "\n")
    if sc:
        print("## Phase H, blind\n")
        print("| model | rms W | bias W | worst W | rms / S2 | E149 rms W |\n|---|---|---|---|---|---|")
        for m, v in sc["models"].items():
            e9 = (s149 or {}).get("models", {}).get(m, {}).get("rms_w")
            print(f"| {m} | {f(v['rms_w'])} | {f(v['bias_w'])} | {f(v['max_abs_w'])} | {f(v['rms_over_span'], 3)} | "
                  f"{f(e9)} |")
        for a, v in sc["arms"].items():
            print(f"| arm {a} | {f(v['rms_w'])} | {f(v['bias_w'])} | — | {f(v['rms_over_span'], 3)} | — |")
        print()
        print("| kind | measured y (W) | se | G1 pred | err | band ± | G4 err | native err | E149 G1 pred (A100 W) |"
              "\n|---|---|---|---|---|---|---|---|---|")
        for k, v in sorted(sc["per_kind"].items()):
            p9 = (p149 or {}).get("kinds", {}).get(k, {}).get("pred", {}).get("G1")
            print(f"| {k} | {f(v['meas'])} | {f(v['se'])} | {f(v['pred']['G1'])} | {f(v['err']['G1'])} | "
                  f"{f(v['band90_w'])} | {f(v['err']['G4'])} | {f(v['err_arms'].get('G1_native'))} | {f(p9)} |")
        print()
        print("| rule | verdict | numbers |\n|---|---|---|")
        for k, v in sc["rules"].items():
            nums = {a: (round(b, 3) if isinstance(b, float) else b) for a, b in v.items() if a != "verdict"}
            print(f"| {k} | {v['verdict']} | {json.dumps(nums)[:200]} |")
        print()
        hh = sc["heat"]
        if "rms_blind_c" in hh:
            print("heat holds:", {k: round(hh[k], 3) for k in ("rms_blind_c", "bias_blind_c", "rms_corr_c",
                                                                 "bias_corr_c", "rms_measP_c", "bias_measP_c")},
                  "inside", hh["inside"], "of", hh["of"], "\n")
            print("| kind | measured rise °C | registered | corrected | from measured P | band ± |\n|---|---|---|---|---|---|")
            for k, v in sorted(hh["rows"].items()):
                print(f"| {k} | {f(v['meas_rise_c'], 2)} | {f(v['pred_blind_c'], 2)} | {f(v['pred_corr_c'], 2)} | "
                      f"{f(v['pred_measP_c'], 2)} | {f(v['band90_c'], 2)} |")


if __name__ == "__main__":
    main(sys.argv[1])
